CREATE SEQUENCE IF NOT EXISTS category_id_seq START WITH 1 INCREMENT BY 50;

CREATE SEQUENCE IF NOT EXISTS product_id_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE category
(
    category_id   BIGINT       NOT NULL,
    category_name VARCHAR(255) NOT NULL,
    category_desc VARCHAR(255),
    CONSTRAINT pk_category PRIMARY KEY (category_id)
);

CREATE TABLE file_data
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name      VARCHAR(255),
    type      VARCHAR(255),
    file_path VARCHAR(255),
    file_size BIGINT,
    CONSTRAINT pk_file_data PRIMARY KEY (id)
);

CREATE TABLE product
(
    product_id   BIGINT           NOT NULL,
    product_name VARCHAR(255),
    price        DOUBLE PRECISION NOT NULL,
    qty_in_stock INTEGER,
    product_desc VARCHAR(255),
    image_id     BIGINT,
    CONSTRAINT pk_product PRIMARY KEY (product_id)
);

CREATE TABLE product_category
(
    category_id BIGINT NOT NULL,
    product_id  BIGINT NOT NULL,
    CONSTRAINT pk_product_category PRIMARY KEY (category_id, product_id)
);

ALTER TABLE category
    ADD CONSTRAINT uc_category_category_name UNIQUE (category_name);

ALTER TABLE product
    ADD CONSTRAINT uc_product_image UNIQUE (image_id);

ALTER TABLE product
    ADD CONSTRAINT FK_PRODUCT_ON_IMAGE FOREIGN KEY (image_id) REFERENCES file_data (id);

ALTER TABLE product_category
    ADD CONSTRAINT fk_procat_on_category FOREIGN KEY (category_id) REFERENCES category (category_id);

ALTER TABLE product_category
    ADD CONSTRAINT fk_procat_on_product FOREIGN KEY (product_id) REFERENCES product (product_id);